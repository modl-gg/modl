export function legacyTextureName(modernName: string): string {
  const mapped = LEGACY_TEXTURE_NAMES[modernName];
  if (mapped !== undefined) return mapped;
  if (modernName.startsWith('block/')) return `blocks/${modernName.slice('block/'.length)}`;
  if (modernName.startsWith('item/')) return `items/${modernName.slice('item/'.length)}`;
  return modernName;
}
